    /** @brief Owns a directory under the system's temporary directory for one test. */
    class ScratchDirectory final
    {
        public:
            /** @brief Creates the directory empty. */
            explicit ScratchDirectory(const char* name)
                : path_(std::filesystem::temp_directory_path() / SushiAI::Test::unique_scratch_name(name))
            {
                std::filesystem::remove_all(path_);
                std::filesystem::create_directories(path_);
            }

            /** @brief Removes the directory and what it holds. */
            ~ScratchDirectory()
            {
                std::error_code ignored;
                std::filesystem::remove_all(path_, ignored);
            }

            /** @brief Forbids a copy, which would remove the directory twice. */
            ScratchDirectory(const ScratchDirectory&) = delete;

            /** @brief Forbids copy assignment. */
            ScratchDirectory& operator=(const ScratchDirectory&) = delete;

            /** @brief Forbids a move, which would leave two owners of one path. */
            ScratchDirectory(ScratchDirectory&&) = delete;

            /** @brief Forbids move assignment. */
            ScratchDirectory& operator=(ScratchDirectory&&) = delete;

            /** @brief Returns the directory. */
            [[nodiscard]] const std::filesystem::path& path() const noexcept { return path_; }

            /** @brief Writes bytes to a file of the directory and returns its path. */
            std::filesystem::path write(const char* name, std::string_view bytes) const
            {
                const std::filesystem::path file = path_ / name;
                std::ofstream out(file, std::ios::binary | std::ios::trunc);
                out.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
                return file;
            }

        private:
            /// @brief Holds the directory this object created and removes.
            std::filesystem::path path_;
    };

    /**
     * @brief Returns bytes drawn from an alphabet by a generator, one draw per byte.
     * @pre @p alphabet is not empty.
     */
    inline std::string drawn_bytes(std::mt19937& generator, std::size_t count,
                                   std::string_view alphabet)
    {
        std::string bytes(count, '\0');
        for (char& byte : bytes)
            byte = alphabet[generator() % alphabet.size()];

        return bytes;
    }

    /** @brief Returns bytes of every value, drawn by a generator, one draw per byte. */
    inline std::string drawn_bytes(std::mt19937& generator, std::size_t count)
    {
        std::string bytes(count, '\0');
        for (char& byte : bytes)
            byte = static_cast<char>(static_cast<std::uint8_t>(generator() & 0xFFu));

        return bytes;
    }
    /** @brief Expects two vocabularies to hold the same merges in the same order. */
    inline void expect_same_merges(const Vocabulary& first, const Vocabulary& second)
    {
        ASSERT_EQ(first.merges().size(), second.merges().size());
        for (std::size_t i = 0; i < first.merges().size(); ++i)
            EXPECT_EQ(first.merges()[i], second.merges()[i]) << "merge " << i;
    }

    /** @brief Expects the merges of @p prefix to be the first merges of @p whole, in order. */
    inline void expect_merges_begin_with(const Vocabulary& whole, const Vocabulary& prefix)
    {
        ASSERT_GE(whole.merges().size(), prefix.merges().size());
        for (std::size_t i = 0; i < prefix.merges().size(); ++i)
            EXPECT_EQ(prefix.merges()[i], whole.merges()[i]) << "merge " << i;
    }

    /**
     * @brief Returns @p count merges that each join the token before them with itself.
     *
     * The first merge joins 'a' with 'a'. Merge i stands for 2^(i + 1) bytes of 'a', and its token
     * has the id 257 + i.
     */
    inline std::vector<Merge> doubling_merges(std::size_t count)
    {
        std::vector<Merge> merges;
        for (std::size_t i = 0; i < count; ++i)
        {
            const TokenID token = i == 0 ? TokenID{97} : static_cast<TokenID>(256 + i);
            merges.push_back(Merge{token, token});
        }

        return merges;
    }

    /** @brief Expects a failure of @p code whose message holds every one of @p needles. */
    template <typename Outcome>
    void expect_failure_naming(const Outcome& outcome, StatusCode code,
                               const std::vector<std::string>& needles)
    {
        const Status status = ::SushiAI::Detail::status_of(outcome);
        EXPECT_EQ(status.code(), code) << status.message();
        for (const std::string& needle : needles)
            EXPECT_NE(status.message().find(needle), std::string_view::npos)
                << "the message does not name \"" << needle << "\": " << status.message();
    }
