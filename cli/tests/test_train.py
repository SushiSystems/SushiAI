"""End-to-end checks for `sushiai train` and `sushiai inference`.

Like test_demo.py these shell out to the installed CLI and a real build tree,
because the thing worth guarding is the whole path - CLI -> app binary ->
printed contract - and no in-process test can see it.

What is deliberately NOT checked here is the argument surface. Both commands
forward verbatim, so restating their arguments in Typer would give two places
to change and one to forget; the diagnostics below come from the C++ side and
this file asserts that they reach the caller intact.

They skip (rather than fail) when the CLI is not installed or the tree has not
been built, since neither is true in a clean checkout. The same claims are
pinned inside CTest, where they always run: see the two
`Integration_App.*` entries in tests/CMakeLists.txt.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import pytest

# cli/tests/test_train.py -> cli/tests -> cli -> <repo root>
REPO_ROOT = Path(__file__).resolve().parents[2]

_COMPILE_ONCE = re.compile(r"compiles\s*:\s*1\b")

# Generated by tests/CMakeLists.txt into the build tree, because a train.json's
# relative paths resolve against its own directory and a committed one would
# write its checkpoint into the source tree.
_TRAIN_CONFIG = REPO_ROOT / "build" / "tests" / "fixtures" / "tiny_train.json"
_CHECKPOINT = REPO_ROOT / "build" / "tests" / "fixtures" / "tiny.ckpt"
_MODEL_CONFIG = REPO_ROOT / "tests" / "fixtures" / "tiny_model.json"
_EVAL_CONFIG = REPO_ROOT / "tests" / "fixtures" / "tiny_eval.json"

_needs_cli = pytest.mark.skipif(
    shutil.which("sushiai") is None, reason="the `sushiai` CLI is not on PATH")
_needs_build = pytest.mark.skipif(
    not _TRAIN_CONFIG.is_file(), reason="no build tree — run `sa build` first")


def _run(*args: str) -> subprocess.CompletedProcess:
    # encoding is stated rather than left to the locale: the CLI's help screen
    # is Rich-rendered and carries box-drawing characters, which a cp1252
    # default cannot decode - and the failure is not an exception the caller
    # sees but a `stdout` that silently comes back as None.
    return subprocess.run(
        ["sushiai", *args], cwd=REPO_ROOT, capture_output=True,
        encoding="utf-8", errors="replace", timeout=900)


@_needs_cli
@_needs_build
def test_sushiai_train_runs_and_reports_one_compile():
    """`sushiai train <train.json>` exits 0 and compiles the step exactly once."""
    completed = _run("train", str(_TRAIN_CONFIG))

    assert completed.returncode == 0, completed.stdout + completed.stderr
    assert _COMPILE_ONCE.search(completed.stdout), completed.stdout
    assert _CHECKPOINT.is_file(), "train did not write the checkpoint it was asked for"


@_needs_cli
@_needs_build
def test_sushiai_inference_loads_the_checkpoint_train_wrote():
    """`sushiai inference` reads a checkpoint and reports one compile."""
    # Ordered by the file, not by a fixture: the training test above is what
    # writes the checkpoint, so run it here too rather than depending on
    # pytest's collection order.
    _run("train", str(_TRAIN_CONFIG))

    completed = _run("inference", str(_MODEL_CONFIG), str(_CHECKPOINT), str(_EVAL_CONFIG))

    assert completed.returncode == 0, completed.stdout + completed.stderr
    assert _COMPILE_ONCE.search(completed.stdout), completed.stdout


@_needs_cli
@_needs_build
def test_both_commands_appear_in_the_top_level_help():
    """They are subcommands of the same app `sa` is, not a separate program."""
    completed = _run("--help")

    assert completed.returncode == 0, completed.stdout + completed.stderr
    assert "train" in completed.stdout
    assert "inference" in completed.stdout


@_needs_cli
@_needs_build
def test_a_wrong_document_kind_is_refused_with_the_librarys_own_message():
    """The C++ diagnostic reaches the caller rather than being swallowed.

    A model.json handed to `train` must not be read as a train.json: every
    configuration document leads with its version key precisely so that this
    is an error rather than a misread.
    """
    completed = _run("train", str(_MODEL_CONFIG))

    assert completed.returncode != 0
    combined = completed.stdout + completed.stderr
    assert "sushiai_train" in combined, combined


@_needs_cli
@_needs_build
def test_a_missing_config_names_the_path():
    """An absent file is refused by name rather than by a generic failure."""
    completed = _run("train", "no/such/train.json")

    assert completed.returncode != 0
    combined = completed.stdout + completed.stderr
    assert "no/such/train.json" in combined, combined
